import { pieces, type Component, type Layout } from './model.ts';

// Positions a piece by the south-west corner of its footprint, so layouts read in room coordinates.
export function at<T extends Component>(c: T, minX: number, minY: number): T {
	const probe = { ...c, x: 0, y: 0 };
	const pts = pieces(probe).flatMap(p => p.poly);
	const x1 = Math.min(...pts.map(p => p.x)),
		y1 = Math.min(...pts.map(p => p.y));
	return { ...c, x: Math.round((minX - x1) * 10) / 10, y: Math.round((minY - y1) * 10) / 10 };
}

