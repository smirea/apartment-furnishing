/**
 * The one bridge from env-manager project `apartment-furnishing` to the Worker, GitHub, and the iOS app.
 * Never prints a value: it logs key names only and hands values to child processes on stdin.
 *
 *   bun scripts/secrets.ts push     prod's API_TOKEN onto the Worker
 *   bun scripts/secrets.ts github   the deploy's Cloudflare credentials as repository secrets
 *   bun scripts/secrets.ts check    drift between env-manager prod, the Worker, and GitHub
 *   bun scripts/secrets.ts verify   CI, before deploying: the Worker has every required secret (no AWS)
 *   bun scripts/secrets.ts ios      prod's API_TOKEN into app-ios/Config/LocalSecrets.xcconfig
 */
import { spawnSync } from 'node:child_process';
import { chmodSync, writeFileSync } from 'node:fs';
import { readEnv, type Values } from './lib';

const REPO = 'smirea/apartment-furnishing';
const WORKER_SECRETS = ['API_TOKEN'] as const;
const CLOUDFLARE_SECRETS = ['CLOUDFLARE_API_TOKEN', 'CLOUDFLARE_ACCOUNT_ID'] as const;
const SERVER_DIR = new URL('../apps/server/', import.meta.url).pathname;
const IOS_CONFIG_PATH = new URL('../app-ios/Config/LocalSecrets.xcconfig', import.meta.url).pathname;

function require(values: Values, names: readonly string[]): Values {
	const missing = names.filter(name => !values[name]);
	if (missing.length) throw new Error(`Not set in env-manager prod: ${missing.join(', ')}`);
	return Object.fromEntries(names.map(name => [name, values[name]!]));
}

function run(command: string[], options: { stdin?: string; env?: Values } = {}): string {
	const result = spawnSync(command[0]!, command.slice(1), {
		input: options.stdin,
		encoding: 'utf8',
		cwd: SERVER_DIR,
		stdio: ['pipe', 'pipe', 'inherit'],
		env: { ...process.env, ...options.env },
	});
	if (result.status !== 0) throw new Error(`${command.slice(0, 3).join(' ')} failed`);
	return result.stdout;
}

/** Wrangler can print a banner before its JSON. */
function workerSecretNames(cloudflare: Values): Set<string> {
	const output = run(['bunx', 'wrangler', 'secret', 'list', '--format', 'json'], { env: cloudflare });
	return new Set((JSON.parse(output.slice(output.indexOf('['))) as { name: string }[]).map(secret => secret.name));
}

function push() {
	const values = readEnv('prod');
	const secrets = require(values, WORKER_SECRETS);
	run(['bunx', 'wrangler', 'secret', 'bulk'], {
		stdin: JSON.stringify(secrets),
		env: require(values, CLOUDFLARE_SECRETS),
	});
	console.log(`Pushed to the Worker: ${Object.keys(secrets).join(', ')}`);
}

function github() {
	for (const [name, value] of Object.entries(require(readEnv('prod'), CLOUDFLARE_SECRETS))) {
		run(['gh', 'secret', 'set', name, '--repo', REPO], { stdin: value });
		console.log(`Set GitHub secret ${name}`);
	}
}

function check() {
	const values = readEnv('prod');
	const onWorker = workerSecretNames(require(values, CLOUDFLARE_SECRETS));
	const onGithub = new Set(
		(JSON.parse(run(['gh', 'secret', 'list', '--repo', REPO, '--json', 'name'])) as { name: string }[]).map(
			secret => secret.name,
		),
	);
	const rows = [
		...WORKER_SECRETS.map(name => ({ name, where: 'Worker', ok: Boolean(values[name]) && onWorker.has(name) })),
		...CLOUDFLARE_SECRETS.map(name => ({ name, where: 'GitHub', ok: Boolean(values[name]) && onGithub.has(name) })),
	];
	for (const row of rows) console.log(`${row.ok ? 'ok   ' : 'DRIFT'} ${row.where} ${row.name}`);
	if (rows.some(row => !row.ok)) process.exit(1);
}

/** Run by CI before `wrangler deploy`, with the Cloudflare credentials in its environment. */
function verify() {
	const onWorker = workerSecretNames({});
	const missing = WORKER_SECRETS.filter(name => !onWorker.has(name));
	if (missing.length) {
		console.error(
			`The Worker lacks ${missing.join(', ')}. Set them in env-manager prod, then run bun run secrets:push.`,
		);
		process.exit(1);
	}
	console.log(`The Worker has every required secret: ${WORKER_SECRETS.join(', ')}`);
}

/** The token ships inside the app: Stefan's own iPhone and iPad are the only installs, so it is as safe as they are. */
function ios() {
	const { API_TOKEN, SERVER_URL } = require(readEnv('prod'), ['API_TOKEN', 'SERVER_URL']);
	// `$()` keeps an xcconfig from reading `//` as the start of a comment.
	writeFileSync(
		IOS_CONFIG_PATH,
		`// Generated by bun run env:ios from env-manager prod. Do not edit.\nAPI_URL = ${SERVER_URL!.replaceAll('//', '/$()/')}\nAPI_TOKEN = ${API_TOKEN}\n`,
	);
	chmodSync(IOS_CONFIG_PATH, 0o600);
	console.log('Wrote API_URL and API_TOKEN to app-ios/Config/LocalSecrets.xcconfig');
}

const commands: Record<string, () => unknown> = { push, github, check, verify, ios };
const command = commands[process.argv[2] ?? ''];
if (!command) {
	console.error(`Usage: bun scripts/secrets.ts <${Object.keys(commands).join('|')}>`);
	process.exit(1);
}
await command();
